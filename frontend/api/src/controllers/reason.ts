/**
 * Creates and configures the Express router for the reasoning endpoint.
 * 
 * @param orchestrator The configured Orchestrator instance
 * @returns Express Router
 */
export const createReasonRouter = (orchestrator: Orchestrator): Router => {
  const router = Router();
  const controller = new ReasonController(orchestrator);
  
  router.post('/', controller.handleReason);
  
  return router;
};

