/**
 * ReasonController
 * 
 * Handles incoming reasoning requests, orchestrates the generation pipeline,
 * and formats the response according to the API contracts. Integrates with
 * Sovereign Halo to expose validation and failure reports.
 */
export class ReasonController {
  constructor(private orchestrator: Orchestrator) {}

  /**
   * Validates the incoming HTTP request payload.
   * 
   * @param req Express Request object
   * @throws Error if validation fails
   */
  private validateRequest(req: Request): ReasonRequest {
    const body = req.body;

    if (!body || typeof body !== 'object') {
      throw new Error('Invalid request body');
    }

    if (!body.query || typeof body.query !== 'string') {
      throw new Error('query is required and must be a string');
    }

    if (!body.identity_anchor || typeof body.identity_anchor !== 'string') {
      throw new Error('identity_anchor is required and must be a string');
    }

    if (body.maxTokens !== undefined && typeof body.maxTokens !== 'number') {
      throw new Error('maxTokens must be a number');
    }

    if (body.temperature !== undefined && typeof body.temperature !== 'number') {
      throw new Error('temperature must be a number');
    }

    return body as ReasonRequest;
  }

  /**
   * Builds a FailureReport from a failed ValidationReport.
   * 
   * @param validationReport The failed validation report
   * @param identity The identity used for validation
   * @param fallbackText The safe fallback text generated by the orchestrator
   * @returns A structured FailureReport
   */
  private buildFailureReport(
    validationReport: ValidationReport,
    identity: SigilIdentity,
    fallbackText: string
  ): FailureReport {
    const violationSummary = validationReport.checks
      .filter(c => !c.passed)
      .map(c => c.detail);

    return {
      status: 'failed',
      attemptCount: validationReport.attemptNumber || 3,
      violationSummary,
      safeFallbackMessage: fallbackText,
      lastValidationReport: validationReport,
      identityId: identity.id,
      generatedAt: new Date().toISOString()
    };
  }

  /**
   * Main handler for the /v1/reason endpoint.
   * 
   * @param req Express Request
   * @param res Express Response
   */
  public handleReason = async (req: Request, res: Response): Promise<void> => {
    try {
      // 1. Validate Request
      const reasonReq = this.validateRequest(req);

      // 2. Resolve Identity
      let identity: SigilIdentity | null = null;
      if (this.orchestrator.identityBinding) {
        identity = await this.orchestrator.identityBinding.resolveOrThrow(reasonReq.identity_anchor);
      }

      // 3. Execute Orchestrator Pipeline
      const orchestratorReq: OrchestratorRequest = {
        query: reasonReq.query,
        identity_anchor: reasonReq.identity_anchor,
        maxTokens: reasonReq.maxTokens,
        temperature: reasonReq.temperature
      };

      const result: OrchestratorResponse = await this.orchestrator.process(orchestratorReq);

      // 4. Determine Status and Reports
      let status: ReasonResponse['status'] = result.reflectiveResult?.status || 'approved';
      let failureReport: FailureReport | undefined;

      if (result.validationReport) {
        if (result.validationReport.status === 'failed') {
          status = 'failed';
          if (identity) {
            failureReport = this.buildFailureReport(result.validationReport, identity, result.text);
          }
        } else {
          status = 'approved';
        }
      }

      // 5. Construct Response
      const response: ReasonResponse = {
        id: result.id,
        output: result.text,
        status,
        identity_anchor: reasonReq.identity_anchor,
        reasoning: {
          orchestrator: result.context,
          reflective: result.reflectiveResult,
          trace: [
            {
              step: 'orchestration_complete',
              timestamp: new Date().toISOString(),
              details: { provider: result.context.selectedProvider }
            }
          ]
        },
        toolCalls: result.toolCalls,
        validationReport: result.validationReport,
        failureReport,
        apiVersion: '1.0.0',
        identity: identity ? {
          id: identity.id,
          name: identity.name,
          version: 1
        } : undefined
      };

      res.status(200).json(response);

    } catch (error: any) {
      console.error(`[ReasonController] Error processing request:`, error);
      
      if (error.code === 'IDENTITY_NOT_FOUND') {
        res.status(404).json({ 
          error: error.message, 
          type: 'ProblemDetails',
          status: 404
        });
      } else {
        res.status(400).json({ 
          error: error.message || 'Bad Request',
          status: 400
        });
      }
    }
  };
}

