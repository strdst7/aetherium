/**
 * Extended Documentation: Sovereign Halo Integration
 * 
 * The ReasonController acts as the primary boundary between the external API
 * consumers and the internal reasoning engine. With the introduction of Phase 7
 * (Sovereign Halo), this controller is responsible for exposing the rigorous
 * validation checks performed on the LLM outputs.
 * 
 * When an output is generated, it passes through the SovereignHaloService.
 * If it violates identity constraints (forbidden behaviors, tone deviation, 
 * symbolic drift), the Orchestrator attempts to regenerate it up to 
 * MAX_HALO_ATTEMPTS times.
 * 
 * If regeneration succeeds, the final `validationReport` is attached to the 
 * response, and the status is set to 'approved'.
 * 
 * If all regeneration attempts fail, the Orchestrator returns a safe fallback 
 * message. The ReasonController detects this failure state, sets the status 
 * to 'failed', and constructs a comprehensive `FailureReport` detailing exactly 
 * which rules were violated.
 */

export type ExtendedReasoningContext = {
  /** The original user query */
  originalQuery: string;
  /** The resolved identity anchor */
  resolvedAnchor: string;
  /** The timestamp when processing began */
  startTime: number;
  /** The timestamp when processing completed */
  endTime: number;
  /** Total processing duration in milliseconds */
  durationMs: number;
};

/**
 * Helper function to calculate processing duration.
 * @param start Start timestamp
 * @param end End timestamp
 * @returns Duration in milliseconds
 */
export const calculateDuration = (start: number, end: number): number => {
  return end - start;
};

/**
 * Helper function to sanitize output text for logging.
 * @param text The raw text
 * @returns Sanitized text
 */
export const sanitizeForLogging = (text: string): string => {
  if (!text) return '';
  return text.replace(/[\r\n]+/g, ' ').substring(0, 100) + '...';
};

